use super::locale::Locale;

/// Static lookup function mapping (Locale, Key) -> Translated string slice.
pub fn lookup_in_locale(locale: Locale, key: &str) -> Option<&'static str> {
    match locale {
        Locale::ZhCn => lookup_zh_cn(key),
        Locale::EnUs => lookup_en_us(key),
        Locale::ZhTw => lookup_zh_tw(key),
        Locale::JaJp => lookup_ja_jp(key),
    }
}

